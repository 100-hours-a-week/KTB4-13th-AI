-- ===========================================================================
-- 책 표에 ISBN 칸을 넣는다 (이슈 #309, 작업 목차 #308)
--
-- BE 와 책을 주고받는 키를 책 번호(book_id)에서 ISBN 으로 바꾼다(#307). 책 번호는 BE 가 책을
-- 넣는 순서대로 매겨서, 다시 넣으면 같은 책이 다른 번호를 받는다. ISBN 은 바뀌지 않는다.
-- AI 안에서는 지금처럼 book_id 로 잇고, 이 칸은 BE 와 주고받을 때 책을 찾는 데만 쓴다.
--
-- 칸: 13자리 숫자만 받는다. 하이픈이나 10자리 ISBN 이 섞이면 같은 책을 다른 책으로 본다.
--     이름은 BE books.isbn13 과 같다. 값은 BE 에서 받아 나중에 채우므로 지금은 비워 둘 수 있다.
--     다 채운 뒤 NOT NULL 을 건다(#308 마지막 단계).
-- 색인: 같은 ISBN 이 두 책에 들어가지 못하게 한다. 빈 값끼리는 겹친 것으로 보지 않는다.
--
-- 칸이 이미 있으면 제약까지 통째로 건너뛴다(IF NOT EXISTS).
-- CONCURRENTLY: 복제가 계속 쓰는 표라, 색인을 만드는 동안 쓰기를 막지 않게 한다.
-- 대신 트랜잭션 안에서는 실행할 수 없다. psql -f 로 이 파일만 따로 적용한다.
-- ===========================================================================

ALTER TABLE v_books
    ADD COLUMN IF NOT EXISTS isbn13 text
    CONSTRAINT v_books_isbn13_format CHECK (isbn13 ~ '^[0-9]{13}$');

CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS v_books_isbn13_key
    ON v_books (isbn13);
