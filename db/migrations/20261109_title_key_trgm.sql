-- ===========================================================================
-- 판정과 똑같이 다듬은 제목의 글자 조각 색인 (이슈 #615)
--
-- 책장 사진은 책등에서 읽은 제목으로 책을 찾는다(app/photo/match_shelf.py). 찾은 책이 맞는지 볼
-- 때는 책 제목에서 앞 괄호 말과 부제를 떼고 견주는데, 후보를 고르는 검색은 띄어쓰기만 뺀 제목
-- 색인을 써서 둘이 어긋났다. 그래서 "(…전문가가 알려 주는) 챗GPT시대 기업이 살아남는 법"은 책등을
-- 그대로 읽어도 비슷함이 0.31 이라 후보에 못 들었다. 책 210만 권 중 4.3%(앞 괄호 말 있는 책의
-- 23%, 부제 있는 책의 34%)가 이렇게 못 찾힌다.
--
-- 식은 match_shelf._KEY_TITLE 과 같아야 색인을 탄다: 부제(" : ", "=", " - " 뒤)와 앞 괄호 말을
-- 떼고, NFKC·소문자로 바꾼 뒤 숫자·로마자·한글만 남긴다(match_shelf.key·catalog_forms 와 같은 일).
--
-- 210만 권 기준 만드는 데 12분, 크기 195MB(띄어쓰기를 뺀 제목 색인 203MB). 줄마다 정규식을 돌려서
-- 오래 걸린다. maintenance_work_mem 은 적용하는 세션에서만 올린다(로컬 시험은 1GB):
--   PGOPTIONS='-c maintenance_work_mem=1GB' psql -f db/migrations/20261109_title_key_trgm.sql
--
-- **이 색인을 코드보다 먼저 적용한다.** 없으면 다시 찾는 검색이 210만 권을 한 줄씩 정규식으로 훑어 한 번에 90초를
-- 넘긴다(로컬 평가 DB, 색인이 있으면 0.1초). 사진 한 장의 제한(60초)에 걸려 책장 사진이 모두 504 가 된다.
--
-- CONCURRENTLY: 복제가 계속 쓰는 테이블이라, 색인을 만드는 동안 쓰기를 막지 않게 한다.
-- 대신 트랜잭션 안에서는 실행할 수 없다. psql -f 로 이 파일만 따로 적용한다.
-- ===========================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS v_books_title_key_trgm_idx ON v_books
    USING gin ((regexp_replace(lower(normalize(regexp_replace(regexp_replace(title,
        '\s*[:=]\s*.*$| - .*$', ''), '^\s*\([^)]*\)\s*', ''), NFKC)),
        '[^0-9a-z가-힣]', '', 'g')) gin_trgm_ops);
