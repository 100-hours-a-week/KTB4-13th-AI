-- 저자 이름 목록 색인 (이슈 #655)
--
-- ③ 챗봇은 "한강 책"처럼 저자를 짚으면 저자 칸을 쉼표로 나눈 이름 하나가 통째로 같은 책을 찾는다
-- (app/chat/authors.py). 이름 일부만 같은 한강현·김한강의 책이 섞이지 않게 하려는 것이다.
--
-- 지금 있는 저자 글자 조각 색인(v_books_author_trgm_idx)은 세 글자부터 탄다. "한강"·"이상" 같은 두 글자 이름은
-- 표 전체를 훑어 평가 DB(210만 권)에서 0.8초가 걸린다. 이 색인이 있으면 이름으로 바로 찾는다.
--
-- 식은 app/chat/authors.py 의 NAMES_SQL 과 글자까지 같아야 색인을 탄다.
-- 색인이 없어도 틀린 답은 안 나온다. 두 글자 저자 요청만 그만큼 느려진다.
--
-- CONCURRENTLY: 복제가 계속 쓰는 테이블이라, 색인을 만드는 동안 쓰기를 막지 않게 한다.
-- 대신 트랜잭션 안에서는 실행할 수 없다. psql -f 로 이 파일만 따로 적용한다.
-- ===========================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS v_books_author_names_idx ON v_books
    USING gin ((regexp_split_to_array(btrim(lower(author)), '\s*[;,]\s*')));
