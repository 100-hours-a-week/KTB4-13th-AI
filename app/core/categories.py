def tag_scores(tags: list[str], points: int) -> dict[str, int]:
    """고른 세부 태그를 카탈로그 분류별 점수로 푼다. 목록에 없는 태그는 건너뛴다.

    같은 분류에 이어진 태그를 여럿 고르면 점수를 더한다(재테크 + 마케팅 → 경제학 2배). 같은 태그를 두 번
    보내도 한 번만 친다.
    """
    scores: dict[str, int] = {}
    for tag in dict.fromkeys(tags):
        for category in TAG_TO_CATALOG.get(tag, ()):
            scores[category] = scores.get(category, 0) + points
    return scores


def catalog_scores(
    onboarding_categories: list[str], core_points: int, partial_points: int
) -> dict[str, int]:
    """고른 온보딩 카테고리를 카탈로그 분류별 점수로 푼다. 대응표에 없는 값은 건너뛴다.

    여러 개를 고르면 점수를 더한다(소설 + 에세이 → 한국문학은 핵심 + 일부). 같은 값을 두 번
    보내도 한 번만 친다.
    """
    scores: dict[str, int] = {}
    for picked in dict.fromkeys(onboarding_categories):
        match = ONBOARDING_TO_CATALOG.get(picked)
        if match is None:
            continue
        for category in match.core:
            scores[category] = scores.get(category, 0) + core_points
        for category in match.partial:
            scores[category] = scores.get(category, 0) + partial_points
    return scores


# 온보딩 보기에 있지만 분류로 가를 수 없는 값. ①④ 는 400 을 내지 않고 거르지 않은 목록을 준다(#228).
UNFILTERED_ONBOARDING = frozenset({"어린이"})


def filter_categories(name: str) -> tuple[str, ...] | None:
    """①④ 의 category 필터로 쓸 카탈로그 분류. 온보딩 값이면 핵심 분류만, 대응표에 없으면 None.

    일부 분류는 필터에 넣지 않는다. "에세이"로 걸렀는데 한국문학의 소설이 섞여 나오면 안 된다(#110).
    어린이처럼 분류로 가를 수 없는 온보딩 값은 빈 튜플이다. 거르지 않는다는 뜻이다(#228).
    """
    if name in UNFILTERED_ONBOARDING:
        return ()
    match = ONBOARDING_TO_CATALOG.get(name)
    return None if match is None else match.core


def is_onboarding(name: str) -> bool:
    """온보딩 값인지. ①④ 요청의 category 는 이 값만 받는다(#219). 거르지 않는 어린이도 포함한다(#228)."""
    return name in ONBOARDING_TO_CATALOG or name in UNFILTERED_ONBOARDING
