"""③ 말풍선의 공통 말투(#545). 카드·대답 프롬프트(app/routers/chat.py)가 같이 쓴다.

카드·대답·⑦ 프롬프트가 말투를 따로 정해서 한 대화 안에서 목소리가 여럿이었다. 카드 말풍선은 해요체로 짧게 말하는데
⑦은 "장바구니에 담긴 책은 다음과 같습니다: 1. …"처럼 합니다체로 목록을 늘어놓고, 대답 턴은 "이 책에 대해 더 궁금한
점이 있으신가요?"로 맺었다. 이 규칙 하나를 카드·대답 프롬프트에 같은 글로 넣는다.

⑦ 에도 넣어 봤지만 점검 대화(gpt-4o-mini, 26개 한 번씩)에서 합니다체 끝맺음 28% → 21%, "다음과 같습니다" 22% → 26%로
뚜렷이 나아지지 않았고, ⑦ 평가는 돌리지 않아 도구 고르기가 흔들리는지 모른다. 그래서 ⑦ 프롬프트에는 넣지 않았다.
⑦ 도 쓸 수 있게 이 파일은 app/core 에 둔다.

규칙은 10/21 평가 원본(gpt-4o-mini)에서 실제로 나온 말에서 뽑았다. 막아 둔 "추천합니다" 끝맺음이 점검 대화 11/44·대화
평가 42/100이었고, "조건을 바꿨군요!", "조건 변경에 대한 소식을 잘 받았습니다"처럼 바뀐 조건을 따로 알리는 말이 "다른
거 보여줘"에도 나왔다. 카드 프롬프트의 "조건을 바꿨으면 받았다고 짧게 말하고"를 글자 그대로 따른 것이다. "~을
찾으셨군요" 첫마디는 카드 턴의 18~20%였다. 바뀐 조건은 따로 알리지 말고 할 말에 녹인다. Google 대화 설계 가이드의
암묵 확인과 같다 — 들은 것을 되풀이하지 말고 다음 말에 녹이며, 매번 같은 수긍 말로 시작하면 로봇처럼 들린다.

예시는 낱말이 아니라 설명으로 적는다. 카드 프롬프트에 낱말 예시를 적었더니 모델이 사용자가 말하지 않은 분위기를
베꼈다(#410). 같은 까닭으로 가격·주제 같은 값도 예시에 적지 않는다.
"""

import re

# 프롬프트 글자에 그대로 들어간다. 템플릿 자리 표시로 읽히지 않게 중괄호를 쓰지 않는다.
RULES = (
    "말투:\n"
    "- 해요체로 짧게 말한다. 합니다체나 반말을 섞지 않는다.\n"
    '- 사용자가 바꾼 조건을 "조건을 바꿨군요"처럼 따로 알리지 말고 할 말에 녹인다'
    "(예: 가격을 새로 말했으면 그 가격 안에서 다시 골랐다고 말한다).\n"
    '- 사용자의 말을 "~을 찾으셨군요"처럼 되풀이하지 않는다. 사용자가 하지 않은 말을 했다고 하지 않는다.\n'
    '- 쓰지 않는 말: "추천합니다"·"추천드립니다"로 끝맺기, "주어진", "요청 감사합니다", '
    '"궁금한 점이 있으시면 말씀해 주세요", "도움이 되길 바랍니다".\n'
    "- 책을 읽어 본 것처럼 말하지 않는다. 책 내용은 받은 정보에 있는 것만 말한다.\n"
)


# 사용자의 요청을 되풀이하는 첫 문장("파이썬 입문서를 찾으셨군요.", "밝은 분위기의 에세이를 원하시는군요.").
# 말투 규칙과 말풍선 지시로 두 번 막았는데도 점검 대화(gpt-4o-mini)에서 카드 턴의 7/39 → 13/37 → 12/38로 줄지 않았다.
# 이 문장에 사용자가 하지 않은 분위기("부담 없이 읽을 수 있는 시집을 찾으셨네요")가 같이 실리는 일도 잦았다.
# "지치셨군요"처럼 사정에 답하는 말은 남긴다. 찾는 것을 되풀이하는 꼴만 본다.
_ECHO_SENTENCE = re.compile(
    r"^[^.!?]*(찾으셨|찾고 계시|원하셨|원하시는|원하신다|바꾸셨|바꿔 주셨|바꿔주셨)[^.!?]*(군요|네요|죠)[.!]\s*"
)


def without_echo(reply: str) -> str:
    """말풍선이 요청을 되풀이하는 문장으로 시작하면 그 문장을 뺀다. 그 문장뿐이면 그대로 둔다."""
    rest = _ECHO_SENTENCE.sub("", reply, count=1)
    return rest if rest and rest != reply else reply


# 말풍선 끝의 막연한 고르기 질문("어떤 스타일이 끌리세요?", "어느 책이 마음에 드세요?").
# 카드 프롬프트에서 막았는데도 점검 대화에서 카드 턴 질문 30개 중 23개가 이 꼴이었다(gpt-4o-mini). 갈래를 말하지 않으니
# 사용자가 무엇과 무엇 중에 고르는지 모르고, 그 뒤 "2번은 어떤 내용이야?"를 문지기 판정이 책 고르기로 읽어 ⑦로 보냈다.
# 갈래를 직접 말한 질문("입문 쪽이 좋으세요, 실전 쪽이 좋으세요?")은 이 꼴이 아니다.
_VAGUE_QUESTION = re.compile(
    r"(어떤|어느)\s*(스타일|책|한\s*권|쪽|유형|타입|것|게)[^.!?]*(끌리|마음에\s*드|좋으|궁금|흥미)[^.!?]*\?\s*$"
)


def without_vague_question(reply: str) -> str:
    """말풍선이 막연한 고르기 질문으로 끝나면 그 문장을 뺀다. 그 문장뿐이면 그대로 둔다."""
    sentences = sentences_of(reply)
    if len(sentences) > 1 and _VAGUE_QUESTION.search(sentences[-1]):
        return " ".join(sentences[:-1])
    return reply


def sentences_of(text: str) -> list[str]:
    return [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]
