"""검색 상수 한 벌(모드). 검색창은 SEARCH 를 쓴다(#556).

후보를 고르는 선, 상한, 점수 가중치, 두 순위를 합치는 비중처럼 검색 결과를 정하는 값을 한곳에 둔다.
챗봇의 분위기·주제 요청처럼 다른 값이 필요한 곳은 다른 모드를 넘긴다. 평가 도구는 값 하나만 바꾼 모드로
같은 코드를 잰다. 함수는 모드를 받지 않으면 부를 때의 `SEARCH` 를 읽는다(바꿔 끼운 값이 바로 먹는다).
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Mode:
    # ── 키워드 후보 고르기(app/search/keyword.py) ──
    # 한 번에 가져오는 후보 수. 응답에는 이 중 앞에서부터 size 만큼만 나간다.
    # 200 은 벡터 검색 결과와 순위를 합칠 때 쓸 여유분이다(#35).
    keyword_limit: int = 200
    # 낱말들이 평균 이만큼은 맞아야 결과에 넣는다(낱말별 0–1, 제목·저자에 있으면 1에 가깝다).
    # 이 선이 없으면 "꿀벌이 주인공인 그림책" 처럼 낱말이 여럿인 검색어에서 "그림책" 하나만
    # 맞은 책 수십 권이 결과를 채운다. 값은 고정 검색어 25개로 0 부터 0.9 까지 재서 골랐다
    # (측정 기록은 이슈 #35 코멘트).
    min_coverage: float = 0.6
    # 소개글에만 있는 낱말은 절반만 쳐 준다. 그래서 소개글에서만 맞은 책은 선을 못 넘는다.
    # 그런 책은 벡터 검색이 뜻으로 찾는다. min_coverage 를 이 값 아래로 내리거나 이 값을 올리면
    # 후보를 제목·저자에서만 고르는 전제(keyword.py)가 깨지니 같이 고쳐야 한다.
    description_coverage: float = 0.5
    # 색인을 한 번 조회할 때 가져오는 책 수 상한. 흔한 낱말은 수만 권이 걸리는데 그 전부를 채점하면
    # 책 수에 비례해 느려진다(266만 권에서 1초가 넘음, #120). 순서 없이 먼저 찾은 만큼만 가져오므로
    # 제목이 검색어와 똑같은 책은 따로 찾아 늘 넣는다.
    lookup_limit: int = 500
    # 낱말마다 넓힐 때 모으는 후보의 합. 낱말 수로 나눠 낱말마다 이만큼씩만 모은다(최소 lookup_min).
    # 후보마다 낱말별로 소개글을 뒤져 채점하므로 비용은 후보 수에 비례한다. 문장으로 친 검색어("초등학생이
    # 읽기 쉬운 과학 책")는 거의 늘 이 경로로 와서, 낱말마다 500권이면 261만 권에서 키워드 단계만 p95 298ms
    # 였다. 1,000권으로 나누면 131ms 이고, 제목·제목+저자 검색 600개의 1등은 그대로였다(#198).
    lookup_budget: int = 1000
    lookup_min: int = 100
    # 낱말이 여럿이면 모든 낱말이 든 책부터 찾는다. 낱말이 많을수록 그런 책은 오히려 줄어 채점할
    # 것이 몇 권 없다. 이만큼도 안 나오면(오타가 섞였거나 제목에 없는 말을 쳤을 때) 낱말마다 넓힌다.
    min_all_words: int = 10

    # ── 키워드 점수 ──
    # 어디서 맞았는지에 따른 가중치. 제목 > 저자 > 소개글.
    # 소개글은 길어서 흔한 낱말이 우연히 걸리기 쉬우므로 낮게 둔다.
    w_title: float = 3.0
    w_author: float = 2.0
    w_description: float = 0.5
    # 검색어 전체가 제목 전체와 비슷할수록 더 올린다. "마음" 을 치면 제목에 마음이 든 책이
    # 수십 권인데, 그중 제목이 정확히 『마음』 인 책이 맨 위여야 한다.
    w_whole_title: float = 2.0

    # ── 벡터 검색(app/search/vector.py) ──
    # 순위 합치기에 넘길 후보 수. 키워드 쪽(keyword_limit)보다 작게 둔다.
    # 벡터 검색은 관련이 없어도 "그나마 가까운 책"을 무조건 채워 주기 때문에, 길게 받을수록 뒤쪽은 잡음이다.
    vector_limit: int = 50
    # 탐색 폭(ef_search). 홈 추천(vector.EF_SEARCH)과 따로 둔다(#516). 운영(벡터 46만 개)에서 처음 조회가
    # 1000 은 최대 0.57초, 400 은 0.36초였다. 평가 묶음에서 제목 검색 1등은 그대로였고, 서술형 검색은 위 10권
    # nDCG 가 0.619 에서 0.617 로 거의 같았다.
    ef_search: int = 400

    # ── 두 순위 합치기(app/search/service.py, rrf.py) ──
    # 합칠 때 키워드 쪽 등수를 3배로 쳐 준다. 키워드 결과는 낱말이 실제로 들어 있는 책이라 믿을 만하고,
    # 벡터 결과는 관련이 없어도 "그나마 가까운 책"이 항상 채워지기 때문이다.
    # 1:1 이면 제목을 정확히 쳐도 벡터 쪽 1등과 자리를 다퉈 밀린다(측정 기록은 이슈 #35 코멘트).
    keyword_weight: float = 3.0
    vector_weight: float = 1.0
    # RRF 의 k. 원 논문이 제안한 값. 클수록 상위 등수 간 차이가 줄어든다.
    rrf_k: int = 60
    # 가격순·최신순·인기순은 등수를 무시하고 줄을 다시 세운다. 벡터 검색은 관련이 없어도 50권을
    # 채워 주므로 다 넣으면 상관없는 책이 "제일 싸다"는 이유로 1등이 된다. 그래서 벡터 쪽은 앞의
    # 20권만 정렬 대상에 넣는다. 고정 검색어 40개로 재니 벡터가 찾아낸 정답은 20등 안이 84%,
    # 50등까지 넓히면 100% 였다. 남은 16%를 얻자고 관련이 약한 30권을 들이는 쪽이 손해라고 봤다.
    sort_vector_limit: int = 20


# 검색창 모드. 검색창과 챗봇의 제목·저자 요청이 쓴다.
SEARCH = Mode()


def current(mode: Mode | None) -> Mode:
    """받은 모드, 없으면 부를 때의 SEARCH."""
    return mode if mode is not None else SEARCH
